import { PrismaClient } from "@prisma/client";

const prisma = new PrismaClient();

// Список источников — после прямой проверки правил использования на каждом
// сайте (жовтень 2026). Из первоначальных 7 реально безопасны для рерайта
// без письменного разрешения только 2 — остальные официально запрещают это:
//
// ИСКЛЮЧЕНЫ (правила сайта прямо запрещают копирование/рерайт для коммерческого
// использования без письменного разрешения):
//   - УНІАН          — "суворо заборонено без письмової згоди"
//   - NV.ua          — платная подписочная модель, разрешения на рерайт нет
//   - Українська правда — "копіювання без письмової згоди адміністрації заборонено"
//   - Фокус          — использование большего объёма текста требует письменного разрешения
//   - Факти ICTV     — явно: "тільки для особистого некомерційного користання"
//   - Interfax-Ukraine — "суворо заборонено" (исключён ранее)
//
// ОСТАВЛЕНЫ (явно разрешают использование с атрибуцией):
const SOURCES = [
  { name: "ZN.UA", rssUrl: "https://zn.ua/rss/full.rss" },
  // Euromaidan Press разрешает ссылку + цитату до 500 знаков свободно;
  // наш рерайт длиннее исходного summary, но короче полной статьи —
  // при реальном запуске стоит держаться ближе к короткому пересказу
  // именно для этого источника, не разворачивать на полные 1500 знаков.
  { name: "Euromaidan Press", rssUrl: "https://euromaidanpress.com/feed/" },
  // Radio Svoboda (укр. служба RFE/RL, фінансується Конгресом США) —
  // "RFE/RL welcomes the reuse, republication, and redistribution of
  // text-based content" з атрибуцією і посиланням. Єдина обмовка в їхніх
  // правилах — пряма заборона "use of RFE/RL content to train AI systems";
  // це, строго кажучи, про навчання моделей, а не про разовий рерайт через
  // LLM, але це сіра зона — варто мати на увазі при реальному запуску.
  // Розділ "Україна", повний список фідів: radiosvoboda.org/rssfeeds
  { name: "Радіо Свобода", rssUrl: "https://www.radiosvoboda.org/api/zqqirl-vomx-tpeiumo" },
];

// Источников 3 — лучше, чем было, но для полноценного продукта всё ещё мало.
// Варианты дальнейшего расширения:
// 1) UAinfo.org — на сайте написано "використання матеріалів дозволяється за
//    умови посилання", но точный RSS URL не подтверждён — проверить вручную.
// 2) Другие западные гос.финансируемые медиа про Украину (Voice of America
//    Ukrainian, подобные RFE/RL по модели) — не проверялись, стоит проверить.
// 3) Связаться напрямую с частью исключённых изданий (УНІАН, Правда, NV.ua,
//    Фокус, Факти) и запросить разрешение на автоматический рерайт с
//    атрибуцией — некоторые дают его по отдельной договорённости, это не
//    исследовалось.
// 4) Пересмотреть модель: вместо полного рерайта — короткая агрегация
//    заголовок+ссылка (без тела текста), это снимает риск почти полностью,
//    но меняет продукт.

async function main() {
  for (const s of SOURCES) {
    await prisma.source.upsert({
      where: { rssUrl: s.rssUrl },
      update: { name: s.name, isActive: true },
      create: { ...s, pollIntervalMinutes: 30 },
    });
  }
  console.log(`Seeded ${SOURCES.length} sources.`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
